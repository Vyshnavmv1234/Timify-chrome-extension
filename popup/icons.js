/**
 * Injects SVG icons into elements with a data-icon attribute.
 * @returns {void}
 */
export function injectIcons() {
  document.querySelectorAll('[data-icon]').forEach((el) => {
    const name = el.getAttribute('data-icon');
    if (name && icons[name]) {
      el.innerHTML = icons[name];
    }
  });
}
